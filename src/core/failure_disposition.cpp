FailureDispositionResult resolve_failure_disposition(const Failure& failure) noexcept {
 for (const Rule& rule : rules) {
  if (failure.failure_id == rule.id)
   return {FailureDispositionStatus::KnownPreliminary, rule.id, rule.reaction};
 }
 return {FailureDispositionStatus::UnknownFailure, failure.failure_id, {}};
}
